"""Pack rendered frames into the app's files.  python pack.py <frames dir> <slug> [slug ...]
Writes public/exercises/<slug>/loop.webp (animated, alpha) and poster.webp (the finish pose), then refreshes
src/lib/rendered-exercises.ts, the list of lifts that have a render (the app falls back to the old photos for the rest)."""
import glob
import os
import sys
from PIL import Image

OUT = 360
frames_dir, slugs = sys.argv[1], sys.argv[2:]
for slug in slugs:
    files = sorted(glob.glob(os.path.join(frames_dir, slug, "f*.png")))
    assert files, "no frames for " + slug
    ims = [Image.open(f).convert("RGBA").resize((OUT, OUT), Image.LANCZOS) for f in files]
    d = os.path.join("public", "exercises", slug)
    os.makedirs(d, exist_ok=True)
    ims[0].save(os.path.join(d, "loop.webp"), save_all=True, append_images=ims[1:], duration=50, loop=0, quality=58, alpha_quality=55, method=6)
    ims[len(ims) // 2].save(os.path.join(d, "poster.webp"), quality=78, alpha_quality=80, method=6)
    print(slug, len(ims), "frames", os.path.getsize(os.path.join(d, "loop.webp")) // 1024, "KB")

have = sorted(p.split(os.sep)[-2] for p in glob.glob(os.path.join("public", "exercises", "*", "loop.webp")))
with open(os.path.join("src", "lib", "rendered-exercises.ts"), "w", encoding="utf-8") as f:
    f.write("// Lifts that have our own 3D render (public/exercises/<slug>/loop.webp). Generated by scripts/exercise-renders/pack.py.\n")
    f.write("export const RENDERED = new Set<string>(" + repr(have).replace("'", '"') + ");\n")
