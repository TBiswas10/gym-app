"""Publish rendered lifts to the app.  python pack.py <renders dir> [slug ...]   (no slugs = every folder with a video)
Copies loop.mp4, makes poster.webp from poster.png, and writes src/lib/rendered-exercises.ts (which lifts have a render,
the muscles lit and the tempo, read from the lift definitions)."""
import glob, os, re, shutil, sys
from PIL import Image

src = sys.argv[1]
slugs = sys.argv[2:] or sorted(os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(src, "*", "loop0001-*.mp4")))
for slug in slugs:
    vids = glob.glob(os.path.join(src, slug, "loop0001-*.mp4"))
    if not vids:
        print("no video for", slug); continue
    d = os.path.join("public", "exercises", slug)
    os.makedirs(d, exist_ok=True)
    shutil.copy(vids[0], os.path.join(d, "loop.mp4"))
    png = os.path.join(src, slug, "poster.png")
    if os.path.exists(png):
        Image.open(png).convert("RGBA").save(os.path.join(d, "poster.webp"), quality=80, alpha_quality=85, method=6)
    for old in ("loop.webp",):
        p = os.path.join(d, old)
        if os.path.exists(p): os.remove(p)
    print(slug, os.path.getsize(os.path.join(d, "loop.mp4")) // 1024, "KB")

text = "".join(open(f, encoding="utf-8").read() for f in glob.glob("scripts/exercise-renders/lifts*.py"))
meta = {}
for m in re.finditer(r'slug="(\w+)",(.*?)props=', text, re.S):
    slug, body = m.group(1), m.group(2)
    h = re.search(r'highlight=\(([^)]*)\)', body); s = re.search(r'secondary=\(([^)]*)\)', body); t = re.search(r'tempo=\(([^)]*)\)', body)
    names = lambda x: re.findall(r'"(\w+)"', x.group(1)) if x else []
    meta[slug] = {"main": names(h), "helpers": names(s), "tempo": [float(v) for v in t.group(1).split(",")] if t else [1.0, 0.45, 2.2, 0.35]}
have = sorted(p.split(os.sep)[-2] for p in glob.glob(os.path.join("public", "exercises", "*", "loop.mp4")))
import json
with open(os.path.join("src", "lib", "rendered-exercises.ts"), "w", encoding="utf-8") as f:
    f.write("// Lifts that have our own 3D render (public/exercises/<slug>/loop.mp4 + poster.webp), the muscles lit and the rep tempo (s: lift, hold, lower, rest).\n// Generated by scripts/exercise-renders/pack.py.\n")
    f.write("export interface RenderMeta { main: string[]; helpers: string[]; tempo: [number, number, number, number] }\n")
    f.write("export const RENDER_META: Record<string, RenderMeta> = " + json.dumps({k: meta[k] for k in have if k in meta}, indent=1) + ";\n")
    f.write("export const RENDERED = new Set<string>(Object.keys(RENDER_META));\n")
